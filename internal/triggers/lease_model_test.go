package triggers

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"testing"
	"time"
)

var update = flag.Bool("update", false, "rewrite the formal models under formal/lifecycles")

// triggerLeaseConstants is formal/lifecycles/TriggerLeaseConstants.tla: the
// trigger lease's TTL and its renewal period, a quarter of it, in the whole
// seconds the TLA+ model counts in. The TTL rounds down and the renewal up,
// so the model never gives a lease more room than the code does.
func triggerLeaseConstants() string {
	renew := LeaseTTL / 4
	return fmt.Sprintf(`\* Code generated by TestTriggerLeaseConstants in internal/triggers. DO NOT EDIT.
------------------------ MODULE TriggerLeaseConstants ------------------------
Lease == %d
Renew == %d
=============================================================================
`, LeaseTTL/time.Second, (renew+time.Second-1)/time.Second)
}

// TestTriggerLeaseConstants holds formal/lifecycles/TriggerLeaseConstants.tla
// to the Go constants, so the tla gate checks TriggerLease.tla against the
// TTL and renewal period the engine runs with. Rerun with -update after
// changing one.
func TestTriggerLeaseConstants(t *testing.T) {
	path := filepath.Join("..", "..", "formal", "lifecycles", "TriggerLeaseConstants.tla")
	want := triggerLeaseConstants()
	if *update {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v; rerun with -update", path, err)
	}
	if string(got) != want {
		t.Fatalf("%s differs from the lease constants; rerun go test ./internal/triggers -run TestTriggerLeaseConstants -update\n--- want\n%s--- got\n%s", path, want, got)
	}
}
