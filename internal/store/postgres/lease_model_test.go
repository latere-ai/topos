package postgres

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"testing"
	"time"
)

var update = flag.Bool("update", false, "rewrite the formal models under formal/lifecycles")

// sessionLeaseConstants is formal/lifecycles/SessionLeaseConstants.tla: the
// session lease's TTL and its renewal period, a quarter of it, in the whole
// seconds the TLA+ model counts in. The TTL rounds down and the renewal up,
// so the model never gives a lease more room than the code does.
func sessionLeaseConstants() string {
	renew := DefaultLeaseTTL / 4
	return fmt.Sprintf(`\* Code generated by TestSessionLeaseConstants in internal/store/postgres. DO NOT EDIT.
------------------------ MODULE SessionLeaseConstants ------------------------
Lease == %d
Renew == %d
=============================================================================
`, DefaultLeaseTTL/time.Second, (renew+time.Second-1)/time.Second)
}

// TestSessionLeaseConstants holds formal/lifecycles/SessionLeaseConstants.tla
// to the Go constants, so the tla gate checks SessionLease.tla against the
// TTL and renewal period the store runs with. Rerun with -update after
// changing one.
func TestSessionLeaseConstants(t *testing.T) {
	path := filepath.Join("..", "..", "..", "formal", "lifecycles", "SessionLeaseConstants.tla")
	want := sessionLeaseConstants()
	if *update {
		if err := os.WriteFile(path, []byte(want), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v; rerun with -update", path, err)
	}
	if string(got) != want {
		t.Fatalf("%s differs from the lease constants; rerun go test ./internal/store/postgres -run TestSessionLeaseConstants -update\n--- want\n%s--- got\n%s", path, want, got)
	}
}
